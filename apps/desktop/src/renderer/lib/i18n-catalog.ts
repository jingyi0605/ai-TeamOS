const interpolate = (text: string, values?: TranslationValues): string =>
  values
    ? text.replace(/\{(\w+)\}/g, (_, key: string) =>
        // An explicit null/undefined renders as nothing; a missing key keeps the
        // placeholder visible so the gap is obvious instead of silently dropped.
        key in values ? String(values[key] ?? "") : `{${key}}`
      )
    : text;

/** The English catalog is the complete baseline; other locales are partial by design. */
const catalogs: Record<Locale, Record<string, string>> = {
  "en-US": {},
  "zh-CN": sourceTranslations,
};

/**
 * Resolves one interface string. Missing translations fall back to the English
 * source string instead of a key or an empty value.
 */
export const translate = (locale: Locale, key: string, values?: TranslationValues): string => {
  if (locale === DEFAULT_LOCALE) return interpolate(key, values);
  return interpolate(catalogs[locale][key] ?? key, values);
};

/**
 * The locale of the mounted provider. Module-level helpers (error formatters, pure
 * utilities) cannot call the hook, so they resolve copy through this snapshot.
 */
let currentLocale: Locale = DEFAULT_LOCALE;

export const setCurrentLocale = (locale: Locale): void => {
  currentLocale = locale;
};

/** Translates copy from code that cannot use the `useI18n` hook. */
export const translateCurrent = (key: string, values?: TranslationValues): string =>
  translate(currentLocale, key, values);

/** Report keys that the current catalogs cannot resolve; used by coverage checks. */
export const missingKeys = (keys: Iterable<string>): string[] =>
  [...new Set(keys)].filter((key) => !(key in sourceTranslations)).sort();
